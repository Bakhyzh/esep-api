CREATE TABLE users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id>0),
 email VARCHAR(255) NOT NULL UNIQUE,
 display_name VARCHAR(100) NOT NULL DEFAULT '',
 status VARCHAR(10) NOT NULL DEFAULT 'ACTIVE' CHECK(status IN ('ACTIVE','DISABLED')),
 version BIGINT NOT NULL DEFAULT 1 CHECK(version>0),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE user_identities (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id),
 issuer VARCHAR(512) NOT NULL CHECK(length(btrim(issuer))>0),
 subject VARCHAR(255) NOT NULL CHECK(length(btrim(subject))>0),
 linked_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 linked_by VARCHAR(255) NOT NULL,
 UNIQUE(issuer,subject), UNIQUE(user_id,issuer)
);
-- Transactional Outbox: an event is written in the SAME database transaction as the transfer.
-- Either both the transfer and its event are committed, or neither. A separate publisher
-- reads unpublished rows and sends them to Kafka (at-least-once delivery).
CREATE TABLE outbox_events (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id       UUID          NOT NULL,
    aggregate_type VARCHAR(50)   NOT NULL,
    aggregate_id   BIGINT        NOT NULL,
    event_type     VARCHAR(50)   NOT NULL,
    message_key    VARCHAR(100)  NOT NULL,
    payload        JSONB         NOT NULL,
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    published_at   TIMESTAMPTZ,
    attempts       INT           NOT NULL DEFAULT 0,
    last_error     VARCHAR(1000),
    CONSTRAINT uq_outbox_events_event_id UNIQUE (event_id)
);

-- the publisher only ever looks for unpublished rows in id order: a tiny partial index
CREATE INDEX ix_outbox_events_unpublished ON outbox_events (id) WHERE published_at IS NULL;
