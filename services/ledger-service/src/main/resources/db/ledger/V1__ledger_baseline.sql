-- Independent Ledger baseline. Contains no credential/profile/notification tables.
CREATE TABLE ledger_principals (
    id BIGINT PRIMARY KEY CHECK (id > 0),
    kind VARCHAR(10) NOT NULL DEFAULT 'HUMAN' CHECK (kind IN ('HUMAN','SYSTEM'))
);
CREATE TABLE ledger_identity_bindings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES ledger_principals(id),
    issuer VARCHAR(512) NOT NULL CHECK(length(btrim(issuer)) > 0),
    subject VARCHAR(255) NOT NULL CHECK(length(btrim(subject)) > 0),
    linked_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    linked_by VARCHAR(255) NOT NULL CHECK(length(btrim(linked_by)) > 0),
    UNIQUE(issuer,subject), UNIQUE(user_id,issuer)
);
CREATE TABLE accounts (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT        NOT NULL REFERENCES ledger_principals (id),
    currency   VARCHAR(3)    NOT NULL,
    balance    NUMERIC(19,4) NOT NULL DEFAULT 0,
    version    BIGINT        NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ   NOT NULL DEFAULT now(),
    -- last line of defense: even if the service has a bug, the DB rejects a negative balance
    CONSTRAINT ck_accounts_balance_non_negative CHECK (balance >= 0),
    CONSTRAINT ck_accounts_currency_iso         CHECK (currency ~ '^[A-Z]{3}$')
);

-- PostgreSQL does NOT create indexes for foreign keys automatically
CREATE INDEX ix_accounts_user_id ON accounts (user_id);

CREATE TABLE transactions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type            VARCHAR(20) NOT NULL,
    status          VARCHAR(20) NOT NULL,
    idempotency_key VARCHAR(64) NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by BIGINT NOT NULL REFERENCES ledger_principals(id),
    request_hash VARCHAR(64) NOT NULL,
    CONSTRAINT uq_transactions_created_by_idempotency_key UNIQUE (created_by,idempotency_key),
    CONSTRAINT ck_transactions_type   CHECK (type IN ('TRANSFER', 'DEPOSIT', 'WITHDRAWAL')),
    CONSTRAINT ck_transactions_status CHECK (status IN ('PENDING', 'COMPLETED', 'FAILED'))
);

-- amount is always positive; the sign comes from direction:
-- DEBIT = money leaves the account (-), CREDIT = money enters the account (+)
CREATE TABLE ledger_entries (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id BIGINT        NOT NULL REFERENCES transactions (id),
    account_id     BIGINT        NOT NULL REFERENCES accounts (id),
    amount         NUMERIC(19,4) NOT NULL,
    direction      VARCHAR(6)    NOT NULL,
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_ledger_entries_amount_positive CHECK (amount > 0),
    CONSTRAINT ck_ledger_entries_direction       CHECK (direction IN ('DEBIT', 'CREDIT'))
);

CREATE INDEX ix_ledger_entries_transaction_id ON ledger_entries (transaction_id);
CREATE INDEX ix_ledger_entries_account_id     ON ledger_entries (account_id, created_at);
-- Accounts are never deleted (ledger history must stay consistent), they are closed.
ALTER TABLE accounts
    ADD COLUMN status    VARCHAR(10) NOT NULL DEFAULT 'ACTIVE',
    ADD COLUMN closed_at TIMESTAMPTZ,
    ADD CONSTRAINT ck_accounts_status CHECK (status IN ('ACTIVE', 'CLOSED'));

-- One active account per user per currency. Closed accounts are not counted (partial index).
CREATE UNIQUE INDEX ux_accounts_user_currency_active
    ON accounts (user_id, currency)
    WHERE status = 'ACTIVE';
-- System (funding) accounts are the "outside world" side of deposits and withdrawals.
-- A deposit of 100 to Alice = DEBIT 100 on the system account, CREDIT 100 on Alice's account,
-- so every transaction still sums to zero. System accounts may go negative:
-- their negative balance = total money that entered the system.
ALTER TABLE accounts
    ADD COLUMN type VARCHAR(10) NOT NULL DEFAULT 'USER',
    ADD CONSTRAINT ck_accounts_type CHECK (type IN ('USER', 'SYSTEM'));

ALTER TABLE accounts DROP CONSTRAINT ck_accounts_balance_non_negative;
ALTER TABLE accounts
    ADD CONSTRAINT ck_accounts_balance_non_negative CHECK (type = 'SYSTEM' OR balance >= 0);


-- Transactional Outbox: an event is written in the SAME database transaction as the transfer.
-- Either both the transfer and its event are committed, or neither. A separate publisher
-- reads unpublished rows and sends them to Kafka (at-least-once delivery).
CREATE TABLE outbox_events (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id       UUID          NOT NULL,
    aggregate_type VARCHAR(50)   NOT NULL,
    aggregate_id   BIGINT        NOT NULL,
    event_type     VARCHAR(50)   NOT NULL,
    message_key    VARCHAR(100)  NOT NULL,
    payload        JSONB         NOT NULL,
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    published_at   TIMESTAMPTZ,
    attempts       INT           NOT NULL DEFAULT 0,
    last_error     VARCHAR(1000),
    CONSTRAINT uq_outbox_events_event_id UNIQUE (event_id)
);

-- the publisher only ever looks for unpublished rows in id order: a tiny partial index
CREATE INDEX ix_outbox_events_unpublished ON outbox_events (id) WHERE published_at IS NULL;


CREATE UNIQUE INDEX ux_accounts_system_currency ON accounts(currency) WHERE type='SYSTEM';
