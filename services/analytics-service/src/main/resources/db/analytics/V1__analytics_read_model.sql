-- Analytics read model and local credential-free identity projection.
CREATE TABLE identity_principals (
    id BIGINT PRIMARY KEY CHECK (id > 0),
    kind VARCHAR(10) NOT NULL DEFAULT 'HUMAN' CHECK (kind IN ('HUMAN','SYSTEM'))
);
CREATE TABLE identity_bindings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES identity_principals(id),
    issuer VARCHAR(512) NOT NULL CHECK(length(btrim(issuer)) > 0),
    subject VARCHAR(255) NOT NULL CHECK(length(btrim(subject)) > 0),
    linked_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    linked_by VARCHAR(255) NOT NULL CHECK(length(btrim(linked_by)) > 0),
    UNIQUE(issuer,subject), UNIQUE(user_id,issuer)
);
CREATE TABLE identity_projection_state (
 user_id BIGINT PRIMARY KEY REFERENCES identity_principals(id),
 issuer VARCHAR(512) NOT NULL,
 subject VARCHAR(255) NOT NULL,
 source_version BIGINT NOT NULL CHECK(source_version>0),
 status VARCHAR(10) NOT NULL CHECK(status IN ('ACTIVE','DISABLED')),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(issuer,subject)
);
CREATE TABLE identity_processed_events (
 event_id UUID PRIMARY KEY,
 payload_hash VARCHAR(64) NOT NULL,
 processed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE processed_events (
 event_id UUID PRIMARY KEY,
 payload_hash VARCHAR(64) NOT NULL,
 processed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE analytics_accounts (
 id BIGINT PRIMARY KEY,
 user_id BIGINT NOT NULL,
 type VARCHAR(10) NOT NULL CHECK(type IN ('USER','SYSTEM')),
 currency VARCHAR(3) NOT NULL,
 status VARCHAR(10) NOT NULL DEFAULT 'ACTIVE' CHECK(status IN ('ACTIVE','CLOSED')),
 entity_version BIGINT NOT NULL DEFAULT -1,
 created_at TIMESTAMPTZ NOT NULL,
 closed_at TIMESTAMPTZ
);
CREATE INDEX ix_analytics_accounts_owner_currency ON analytics_accounts(user_id,currency);
CREATE TABLE analytics_transactions (
 id BIGINT PRIMARY KEY,
 type VARCHAR(20) NOT NULL,
 created_at TIMESTAMPTZ NOT NULL,
 semantic_hash VARCHAR(64) NOT NULL
);
CREATE TABLE analytics_entries (
 id BIGINT PRIMARY KEY,
 transaction_id BIGINT NOT NULL REFERENCES analytics_transactions(id),
 account_id BIGINT NOT NULL REFERENCES analytics_accounts(id),
 direction VARCHAR(6) NOT NULL CHECK(direction IN ('DEBIT','CREDIT')),
 amount NUMERIC(19,4) NOT NULL CHECK(amount>0),
 created_at TIMESTAMPTZ NOT NULL,
 semantic_hash VARCHAR(64) NOT NULL
);
CREATE INDEX ix_analytics_entries_tx ON analytics_entries(transaction_id);
CREATE INDEX ix_analytics_entries_debit_account_created ON analytics_entries(account_id,created_at) INCLUDE(amount,transaction_id) WHERE direction='DEBIT';
CREATE TABLE analytics_generations (
 user_id BIGINT PRIMARY KEY,
 generation BIGINT NOT NULL,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
