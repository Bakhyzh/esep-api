-- Additive migration: no user IDs, credentials or financial references are rewritten.
CREATE TABLE user_identities (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id   BIGINT NOT NULL REFERENCES users (id),
    issuer    VARCHAR(512) NOT NULL,
    subject   VARCHAR(255) NOT NULL,
    linked_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    linked_by VARCHAR(255) NOT NULL,
    CONSTRAINT uq_user_identities_issuer_subject UNIQUE (issuer, subject),
    CONSTRAINT uq_user_identities_user_issuer UNIQUE (user_id, issuer),
    CONSTRAINT ck_user_identities_issuer CHECK (length(btrim(issuer)) > 0),
    CONSTRAINT ck_user_identities_subject CHECK (length(btrim(subject)) > 0),
    CONSTRAINT ck_user_identities_linked_by CHECK (length(btrim(linked_by)) > 0)
);

-- Legacy hashes remain intact. Keycloak-only profiles need not have a local password.
ALTER TABLE users ALTER COLUMN password_hash DROP NOT NULL;
